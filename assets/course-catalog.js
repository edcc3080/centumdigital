export const COURSE_MAP =
  Object.fromEntries(
    COURSE_CATALOG.map(course => [
      course.key,
      course
    ])
  );

export function getCourse(key) {
  return COURSE_MAP[key] || COURSE_MAP.other;
}

export function courseDetailHref(key, roundId = "") {
  const safeKey = COURSE_MAP[key] ? key : "other";

  if (safeKey === "other" && roundId) {
    return `국민내일배움카드/course-detail.html?course=other&round=${encodeURIComponent(roundId)}`;
  }

  return `국민내일배움카드/course-detail.html?course=${encodeURIComponent(safeKey)}`;
}

export function courseDetailHrefFromSubpage(key, roundId = "") {
  const safeKey = COURSE_MAP[key] ? key : "other";

  if (safeKey === "other" && roundId) {
    return `course-detail.html?course=other&round=${encodeURIComponent(roundId)}`;
  }

  return `course-detail.html?course=${encodeURIComponent(safeKey)}`;
}
